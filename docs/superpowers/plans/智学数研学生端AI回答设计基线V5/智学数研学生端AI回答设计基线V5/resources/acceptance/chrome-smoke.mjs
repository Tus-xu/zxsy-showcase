async function open(viewport, hash = '', reducedMotion = 'no-preference', blockStorage = false) {
  const context = await browser.newContext({ viewport, offline: true, reducedMotion, locale: 'zh-CN' })
  if (blockStorage) await context.addInitScript(() => {
    Storage.prototype.setItem = () => { throw new DOMException('storage unavailable in this test', 'QuotaExceededError') }
  })
  const page = await context.newPage()
  page.on('pageerror', (error) => report.errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') report.consoleErrors.push(message.text()) })
  page.on('request', (request) => { if (/^(https?|wss?):/.test(request.url())) report.network.push(new URL(request.url()).origin) })
  page.on('websocket', (socket) => report.network.push(new URL(socket.url()).origin))
  await page.goto(url + hash)
  return { context, page }
}

