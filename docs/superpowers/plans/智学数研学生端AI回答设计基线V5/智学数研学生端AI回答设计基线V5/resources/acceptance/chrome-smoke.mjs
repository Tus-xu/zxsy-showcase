async function layout(page, id) {
  const geometry = await page.evaluate(() => {
    const rect = (selector) => document.querySelector(selector).getBoundingClientRect()
    const reading = rect('.thread')
    const input = rect('.composer-inner')
    return {
      reading: Math.round(reading.width), input: Math.round(input.width),
      leftDifference: Math.round(reading.left - input.left),
      overlap: Math.max(0, rect('#scroll').bottom - rect('.composer-area').top),
      overflow: document.documentElement.scrollWidth - innerWidth,
      border: getComputedStyle(document.querySelector('.reply-panel')).borderTopWidth,
    }
  })
  assert.equal(geometry.reading, geometry.input, id)
  assert.ok(Math.abs(geometry.leftDifference) <= 1, id)
  assert.equal(geometry.overlap, 0, id)
  assert.equal(geometry.overflow, 0, id)
  assert.equal(geometry.border, '1px', id)
  report.pages[id] = geometry
}

